using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ESharp.Assets;

/// <summary>
/// Reads an <c>assets.json</c> manifest and generates a C# source file with the images as planar chip RAM
/// data and OCS palettes (or, with <c>"aga": true</c> and up to 256 colours, 24-bit AGA palettes):
/// <code>{ "namespace": "Game", "class": "Assets", "images": [ { "name": "Card", "file": "card.png", "colors": 16, "mask": true } ] }</code>
/// For each image it writes <c>NameWidth</c>, <c>NameHeight</c>, <c>NameDepth</c>, <c>NamePlanes</c> and <c>NamePalette</c>, and <c>NameMask</c> when the entry has <c>"mask": true</c>.
/// </summary>
public static class AssetBuilder
{
    public sealed record Entry(string Name, string File, int Colors, bool Mask = false, bool Aga = false);

    public sealed record Report(string Name, int Width, int Height, int Depth, int ChipBytes);

    public sealed record Output(string Source, IReadOnlyList<Report> Reports);

    public static Output Build(string manifestPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(manifestPath))!;
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        var root = doc.RootElement;
        var ns = root.TryGetProperty("namespace", out var n) ? n.GetString()! : "Assets";
        var cls = root.TryGetProperty("class", out var c) ? c.GetString()! : "Assets";
        var entries = new List<Entry>();
        if (root.TryGetProperty("images", out var images))
            foreach (var e in images.EnumerateArray())
                entries.Add(new Entry(
                    e.GetProperty("name").GetString()!,
                    e.GetProperty("file").GetString()!,
                    e.TryGetProperty("colors", out var col) ? col.GetInt32() : 16,
                    e.TryGetProperty("mask", out var mk) && mk.GetBoolean(),
                    e.TryGetProperty("aga", out var ag) && ag.GetBoolean()));

        // "if": "AROS" wraps the whole file in #if, so an asset set that only some targets use costs the others nothing.
        var condition = root.TryGetProperty("if", out var cond) ? cond.GetString() : null;
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> by `esharp assets` from assets.json. Do not edit; change the manifest and run it again.\n");
        if (condition != null) sb.Append($"#if {condition}\n");
        sb.Append("using ESharp;\n\n");
        sb.Append($"namespace {ns};\n\n");
        sb.Append($"public static class {cls}\n{{\n");
        var reports = new List<Report>();
        foreach (var entry in entries)
        {
            if (!IsIdentifier(entry.Name)) throw new InvalidDataException($"asset name '{entry.Name}' is not a C# identifier");
            var png = Png.Read(File.ReadAllBytes(Path.Combine(dir, entry.File)));
            var planar = Planar.Convert(png, entry.Colors, entry.Aga);
            reports.Add(new Report(entry.Name, planar.Width, planar.Height, planar.Depth, planar.Planes.Length + (entry.Mask ? planar.Mask.Length : 0)));

            sb.Append($"    // {entry.File}: {planar.Width}x{planar.Height}, {planar.Depth} bitplanes, {(entry.Aga ? planar.Palette24.Length : planar.Palette.Length)} colours{(entry.Aga ? " (AGA, 24-bit palette)" : "")}\n");
            sb.Append($"    public const int {entry.Name}Width = {planar.Width};\n");
            sb.Append($"    public const int {entry.Name}Height = {planar.Height};\n");
            sb.Append($"    public const int {entry.Name}Depth = {planar.Depth};\n");
            if (entry.Aga)
                sb.Append($"    /// <summary>0x00RRGGBB, for Video.SetPalette24 (AGA).</summary>\n    public static uint[] {entry.Name}Palette = {{ {string.Join(", ", planar.Palette24.Select(p => "0x" + p.ToString("X6")))} }};\n");
            else
                sb.Append($"    public static ushort[] {entry.Name}Palette = {{ {string.Join(", ", planar.Palette.Select(p => "0x" + p.ToString("X3")))} }};\n");
            sb.Append($"    [ChipRam] public static byte[] {entry.Name}Planes =\n    {{\n");
            for (var i = 0; i < planar.Planes.Length; i += 16)
                sb.Append("        " + string.Join(", ", planar.Planes.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
            sb.Append("    };\n");
            if (entry.Mask)
            {
                sb.Append($"    /// <summary>One plane, 1 = opaque; for Video.BlitMasked.</summary>\n");
                sb.Append($"    [ChipRam] public static byte[] {entry.Name}Mask =\n    {{\n");
                for (var i = 0; i < planar.Mask.Length; i += 16)
                    sb.Append("        " + string.Join(", ", planar.Mask.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
                sb.Append("    };\n");
            }
            sb.Append("\n");
        }
        sb.Append("}\n");
        if (condition != null) sb.Append("#endif\n");
        return new Output(sb.ToString(), reports);
    }

    public enum SyncStatus { UpToDate, Created, Updated, Touched }

    public sealed record SyncResult(SyncStatus Status, string Target, Output? Output);

    /// <summary>The generated file that belongs to a manifest: <c>Assets.g.cs</c> next to it.</summary>
    public static string TargetPath(string manifestPath) =>
        Path.Combine(Path.GetDirectoryName(Path.GetFullPath(manifestPath))!, "Assets.g.cs");

    /// <summary>The files the generated source depends on: the manifest and every PNG it lists.</summary>
    public static IReadOnlyList<string> Inputs(string manifestPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(manifestPath))!;
        var list = new List<string> { Path.GetFullPath(manifestPath) };
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        if (doc.RootElement.TryGetProperty("images", out var images))
            foreach (var e in images.EnumerateArray())
                if (e.TryGetProperty("file", out var f) && f.GetString() is { } name)
                    list.Add(Path.GetFullPath(Path.Combine(dir, name)));
        return list;
    }

    /// <summary>True when <c>Assets.g.cs</c> is missing or older than the manifest or any listed PNG.</summary>
    public static bool IsStale(string manifestPath)
    {
        var target = TargetPath(manifestPath);
        if (!File.Exists(target)) return true;
        var built = File.GetLastWriteTimeUtc(target);
        // A missing PNG counts as stale so that Build reports it.
        return Inputs(manifestPath).Any(i => !File.Exists(i) || File.GetLastWriteTimeUtc(i) > built);
    }

    /// <summary>
    /// Incremental build step: regenerates <c>Assets.g.cs</c> only when it is stale (or <paramref name="force"/>).
    /// The file is rewritten only when the text really changes; if it does not, the file is just touched so
    /// that it is fresh again (the next call is then a no-op and git sees no change).
    /// </summary>
    public static SyncResult Sync(string manifestPath, bool force = false)
    {
        var target = TargetPath(manifestPath);
        if (!force && !IsStale(manifestPath)) return new SyncResult(SyncStatus.UpToDate, target, null);
        var output = Build(manifestPath);
        if (!File.Exists(target))
        {
            File.WriteAllText(target, output.Source);
            return new SyncResult(SyncStatus.Created, target, output);
        }
        if (File.ReadAllText(target) == output.Source)
        {
            // Not older than any input, even one with a future time (clock skew, files from another machine),
            // so the next build is a no-op instead of another regeneration.
            var stamp = DateTime.UtcNow;
            foreach (var i in Inputs(manifestPath))
                if (File.Exists(i) && File.GetLastWriteTimeUtc(i) > stamp) stamp = File.GetLastWriteTimeUtc(i);
            File.SetLastWriteTimeUtc(target, stamp);
            return new SyncResult(SyncStatus.Touched, target, output);
        }
        File.WriteAllText(target, output.Source);
        return new SyncResult(SyncStatus.Updated, target, output);
    }

    private static bool IsIdentifier(string s) =>
        s.Length > 0 && (char.IsLetter(s[0]) || s[0] == '_') && s.All(ch => char.IsLetterOrDigit(ch) || ch == '_');
}
