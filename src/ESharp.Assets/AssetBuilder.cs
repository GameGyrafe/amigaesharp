using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ESharp.Assets;

/// <summary>
/// Reads an <c>assets.json</c> manifest and generates a C# source file with the images as planar chip RAM
/// data and OCS palettes:
/// <code>{ "namespace": "Game", "class": "Assets", "images": [ { "name": "Card", "file": "card.png", "colors": 16, "mask": true } ] }</code>
/// For each image it writes <c>NameWidth</c>, <c>NameHeight</c>, <c>NameDepth</c>, <c>NamePlanes</c> and <c>NamePalette</c>, and <c>NameMask</c> when the entry has <c>"mask": true</c>.
/// </summary>
public static class AssetBuilder
{
    public sealed record Entry(string Name, string File, int Colors, bool Mask = false);

    public sealed record Report(string Name, int Width, int Height, int Depth, int ChipBytes);

    public sealed record Output(string Source, IReadOnlyList<Report> Reports);

    public static Output Build(string manifestPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(manifestPath))!;
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        var root = doc.RootElement;
        var ns = root.TryGetProperty("namespace", out var n) ? n.GetString()! : "Assets";
        var cls = root.TryGetProperty("class", out var c) ? c.GetString()! : "Assets";
        var entries = new List<Entry>();
        if (root.TryGetProperty("images", out var images))
            foreach (var e in images.EnumerateArray())
                entries.Add(new Entry(
                    e.GetProperty("name").GetString()!,
                    e.GetProperty("file").GetString()!,
                    e.TryGetProperty("colors", out var col) ? col.GetInt32() : 16,
                    e.TryGetProperty("mask", out var mk) && mk.GetBoolean()));

        var sb = new StringBuilder();
        sb.Append("// <auto-generated> by `esharp assets` from assets.json. Do not edit; change the manifest and run it again.\n");
        sb.Append("using ESharp;\n\n");
        sb.Append($"namespace {ns};\n\n");
        sb.Append($"public static class {cls}\n{{\n");
        var reports = new List<Report>();
        foreach (var entry in entries)
        {
            if (!IsIdentifier(entry.Name)) throw new InvalidDataException($"asset name '{entry.Name}' is not a C# identifier");
            var png = Png.Read(File.ReadAllBytes(Path.Combine(dir, entry.File)));
            var planar = Planar.Convert(png, entry.Colors);
            reports.Add(new Report(entry.Name, planar.Width, planar.Height, planar.Depth, planar.Planes.Length + (entry.Mask ? planar.Mask.Length : 0)));

            sb.Append($"    // {entry.File}: {planar.Width}x{planar.Height}, {planar.Depth} bitplanes, {planar.Palette.Length} colours\n");
            sb.Append($"    public const int {entry.Name}Width = {planar.Width};\n");
            sb.Append($"    public const int {entry.Name}Height = {planar.Height};\n");
            sb.Append($"    public const int {entry.Name}Depth = {planar.Depth};\n");
            sb.Append($"    public static ushort[] {entry.Name}Palette = {{ {string.Join(", ", planar.Palette.Select(p => "0x" + p.ToString("X3")))} }};\n");
            sb.Append($"    [ChipRam] public static byte[] {entry.Name}Planes =\n    {{\n");
            for (var i = 0; i < planar.Planes.Length; i += 16)
                sb.Append("        " + string.Join(", ", planar.Planes.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
            sb.Append("    };\n");
            if (entry.Mask)
            {
                sb.Append($"    /// <summary>One plane, 1 = opaque; for Video.BlitMasked.</summary>\n");
                sb.Append($"    [ChipRam] public static byte[] {entry.Name}Mask =\n    {{\n");
                for (var i = 0; i < planar.Mask.Length; i += 16)
                    sb.Append("        " + string.Join(", ", planar.Mask.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
                sb.Append("    };\n");
            }
            sb.Append("\n");
        }
        sb.Append("}\n");
        return new Output(sb.ToString(), reports);
    }

    private static bool IsIdentifier(string s) =>
        s.Length > 0 && (char.IsLetter(s[0]) || s[0] == '_') && s.All(ch => char.IsLetterOrDigit(ch) || ch == '_');
}
