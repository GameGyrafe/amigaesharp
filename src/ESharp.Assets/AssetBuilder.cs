using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ESharp.Assets;

/// <summary>
/// Reads an <c>assets.json</c> manifest and generates a C# source file with the images as planar chip RAM
/// data and OCS palettes (or, with <c>"aga": true</c> and up to 256 colours, 24-bit AGA palettes):
/// <code>{ "namespace": "Game", "class": "Assets", "images": [ { "name": "Card", "file": "card.png", "colors": 16, "mask": true } ] }</code>
/// An image may be a PNG or an IFF ILBM file, and <c>"dither": "fs"</c> or <c>"ordered"</c> spreads the colour error when colours are reduced (default none).
/// A <c>"samples"</c> list of WAV or 8SVX files is embedded as 8-bit signed mono chip data: <c>NameData</c>, <c>NameLength</c>, <c>NameRate</c>.
/// A <c>"fonts"</c> list of font images (a grid of equal glyph cells, see <see cref="FontImage"/>) is embedded as glyph bits for <c>ESharp.Platform.BitmapFont</c>:
/// <c>{ "name": "Mini", "file": "mini.png", "cellWidth": 9, "cellHeight": 9, "first": 32, "count": 95, "columns": 16 }</c> (first defaults to 32, columns to as many as fit)
/// writes a nested static class <c>Mini</c> (<c>CellWidth</c>, <c>CellHeight</c>, <c>First</c>, <c>Count</c>, <c>Glyphs</c>, and <c>Has</c>, <c>Pixel</c>, <c>Width</c>, <c>Height</c>, <c>Draw</c>, <c>DrawChar</c>, <c>DrawInt</c> that call <c>ESharp.Platform.BitmapFont</c>).
/// For each image it writes <c>NameWidth</c>, <c>NameHeight</c>, <c>NameDepth</c>, <c>NamePlanes</c> and <c>NamePalette</c>, and <c>NameMask</c> when the entry has <c>"mask": true</c>.
/// </summary>
public static class AssetBuilder
{
    public sealed record Entry(string Name, string File, int Colors, bool Mask = false, bool Aga = false, Dither Dither = Dither.None);

    public sealed record SampleEntry(string Name, string File);

    public sealed record FontEntry(string Name, string File, int CellWidth, int CellHeight, int First, int Count, int Columns);

    public sealed record Report(string Name, int Width, int Height, int Depth, int ChipBytes, bool IsSample = false, bool IsFont = false);

    public sealed record Output(string Source, IReadOnlyList<Report> Reports, IReadOnlyList<string>? Warnings = null);

    public static Output Build(string manifestPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(manifestPath))!;
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        var root = doc.RootElement;
        var ns = root.TryGetProperty("namespace", out var n) ? n.GetString()! : "Assets";
        var cls = root.TryGetProperty("class", out var c) ? c.GetString()! : "Assets";
        var entries = new List<Entry>();
        if (root.TryGetProperty("images", out var images))
            foreach (var e in images.EnumerateArray())
                entries.Add(new Entry(
                    e.GetProperty("name").GetString()!,
                    e.GetProperty("file").GetString()!,
                    e.TryGetProperty("colors", out var col) ? col.GetInt32() : 16,
                    e.TryGetProperty("mask", out var mk) && mk.GetBoolean(),
                    e.TryGetProperty("aga", out var ag) && ag.GetBoolean(),
                    Planar.ParseDither(e.TryGetProperty("dither", out var dt) && dt.ValueKind != JsonValueKind.Null ? dt.GetString() : null)));
        var sampleEntries = new List<SampleEntry>();
        if (root.TryGetProperty("samples", out var samples))
            foreach (var e in samples.EnumerateArray())
                sampleEntries.Add(new SampleEntry(e.GetProperty("name").GetString()!, e.GetProperty("file").GetString()!));
        var fontEntries = new List<FontEntry>();
        if (root.TryGetProperty("fonts", out var fonts))
            foreach (var e in fonts.EnumerateArray())
            {
                int Int(string key, int fallback) => e.TryGetProperty(key, out var v) ? v.GetInt32() : fallback;
                var fontName = e.GetProperty("name").GetString()!;
                if (!e.TryGetProperty("cellWidth", out _) || !e.TryGetProperty("cellHeight", out _))
                    throw new InvalidDataException($"font '{fontName}' needs \"cellWidth\" and \"cellHeight\"");
                if (!e.TryGetProperty("count", out _)) throw new InvalidDataException($"font '{fontName}' needs \"count\"");
                fontEntries.Add(new FontEntry(fontName, e.GetProperty("file").GetString()!, Int("cellWidth", 0), Int("cellHeight", 0), Int("first", 32), Int("count", 0), Int("columns", 0)));
            }
        var warnings = new List<string>();

        // "if": "AROS" wraps the whole file in #if, so an asset set that only some targets use costs the others nothing.
        var condition = root.TryGetProperty("if", out var cond) ? cond.GetString() : null;
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> by `esharp assets` from assets.json. Do not edit; change the manifest and run it again.\n");
        // The inputs this file was made from, by content: a library build (ESL011) compares them with the files as they are now,
        // which file times cannot do (a fresh clone gives every file the time of the checkout, in no useful order).
        sb.Append($"// input sha256:{InputHash(File.ReadAllBytes(manifestPath), text: true)} {Path.GetFileName(manifestPath)}\n");
        foreach (var file in entries.Select(e => e.File).Concat(sampleEntries.Select(e => e.File)).Concat(fontEntries.Select(e => e.File)))
            sb.Append($"// input sha256:{InputHash(File.ReadAllBytes(Path.Combine(dir, file)), text: false)} {file}\n");
        if (condition != null) sb.Append($"#if {condition}\n");
        sb.Append("using ESharp;\n");
        if (fontEntries.Count > 0) sb.Append("using ESharp.Platform;\n");
        sb.Append("\n");
        sb.Append($"namespace {ns};\n\n");
        sb.Append($"public static class {cls}\n{{\n");
        var reports = new List<Report>();
        foreach (var entry in entries)
        {
            if (!IsIdentifier(entry.Name)) throw new InvalidDataException($"asset name '{entry.Name}' is not a C# identifier");
            var png = ImageFile.Read(File.ReadAllBytes(Path.Combine(dir, entry.File)));
            var planar = Planar.Convert(png, entry.Colors, entry.Aga, entry.Dither);
            reports.Add(new Report(entry.Name, planar.Width, planar.Height, planar.Depth, planar.Planes.Length + (entry.Mask ? planar.Mask.Length : 0)));

            sb.Append($"    // {entry.File}: {planar.Width}x{planar.Height}, {planar.Depth} bitplanes, {(entry.Aga ? planar.Palette24.Length : planar.Palette.Length)} colours{(entry.Aga ? " (AGA, 24-bit palette)" : "")}\n");
            sb.Append($"    public const int {entry.Name}Width = {planar.Width};\n");
            sb.Append($"    public const int {entry.Name}Height = {planar.Height};\n");
            sb.Append($"    public const int {entry.Name}Depth = {planar.Depth};\n");
            if (entry.Aga)
                sb.Append($"    /// <summary>0x00RRGGBB, for Video.SetPalette24 (AGA).</summary>\n    public static uint[] {entry.Name}Palette = {{ {string.Join(", ", planar.Palette24.Select(p => "0x" + p.ToString("X6")))} }};\n");
            else
                sb.Append($"    public static ushort[] {entry.Name}Palette = {{ {string.Join(", ", planar.Palette.Select(p => "0x" + p.ToString("X3")))} }};\n");
            sb.Append($"    [ChipRam] public static byte[] {entry.Name}Planes =\n    {{\n");
            for (var i = 0; i < planar.Planes.Length; i += 16)
                sb.Append("        " + string.Join(", ", planar.Planes.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
            sb.Append("    };\n");
            if (entry.Mask)
            {
                sb.Append($"    /// <summary>One plane, 1 = opaque; for Video.BlitMasked.</summary>\n");
                sb.Append($"    [ChipRam] public static byte[] {entry.Name}Mask =\n    {{\n");
                for (var i = 0; i < planar.Mask.Length; i += 16)
                    sb.Append("        " + string.Join(", ", planar.Mask.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
                sb.Append("    };\n");
            }
            sb.Append("\n");
        }
        foreach (var s in sampleEntries)
        {
            if (!IsIdentifier(s.Name)) throw new InvalidDataException($"asset name '{s.Name}' is not a C# identifier");
            var sound = SoundFile.Read(File.ReadAllBytes(Path.Combine(dir, s.File)));
            var data = sound.Data;
            if (data.Length > MaxSampleLength)
            {
                warnings.Add($"{s.File}: {data.Length:N0} samples cut to {MaxSampleLength:N0} (the longest audio.device takes in one write)");
                data = data.Take(MaxSampleLength).ToArray();
            }
            var length = Math.Max(4, (data.Length + 1) & ~1);   // even, at least 4, padded with silence
            var bytes = new byte[length];
            for (var i = 0; i < data.Length; i++) bytes[i] = (byte)data[i];
            reports.Add(new Report(s.Name, length, 1, 8, length, IsSample: true));
            sb.Append($"    // {s.File}: {length} bytes of 8-bit signed mono, {sound.Rate} Hz\n");
            sb.Append($"    public const int {s.Name}Length = {length};\n");
            sb.Append($"    public const int {s.Name}Rate = {sound.Rate};\n");
            sb.Append($"    [ChipRam] public static byte[] {s.Name}Data =\n    {{\n");
            for (var i = 0; i < bytes.Length; i += 16)
                sb.Append("        " + string.Join(", ", bytes.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
            sb.Append("    };\n\n");
        }
        foreach (var f in fontEntries)
        {
            if (!IsIdentifier(f.Name)) throw new InvalidDataException($"asset name '{f.Name}' is not a C# identifier");
            var glyphs = FontImage.Convert(ImageFile.Read(File.ReadAllBytes(Path.Combine(dir, f.File))), f.CellWidth, f.CellHeight, f.First, f.Count, f.Columns);
            if (glyphs.InkPixels == 0) warnings.Add($"{f.File}: no ink pixel in any glyph (every pixel is the background colour of the top-left corner)");
            reports.Add(new Report(f.Name, f.CellWidth, f.CellHeight, 1, glyphs.Data.Length, IsFont: true));
            sb.Append($"    // {f.File}: {f.Count} glyphs of {f.CellWidth}x{f.CellHeight} from character {f.First}, 1 bit per pixel, {(f.CellWidth + 7) / 8} byte(s) per row\n");
            sb.Append($"    public static class {f.Name}\n    {{\n");
            sb.Append($"        public const int CellWidth = {f.CellWidth};\n");
            sb.Append($"        public const int CellHeight = {f.CellHeight};\n");
            sb.Append($"        public const int First = {f.First};\n");
            sb.Append($"        public const int Count = {f.Count};\n");
            sb.Append("        public static byte[] Glyphs =\n        {\n");
            for (var i = 0; i < glyphs.Data.Length; i += 16)
                sb.Append("            " + string.Join(", ", glyphs.Data.Skip(i).Take(16).Select(b => "0x" + b.ToString("X2"))) + ",\n");
            sb.Append("        };\n\n");
            sb.Append("        public static bool Has(char c) { return BitmapFont.Has(First, Count, c); }\n");
            sb.Append("        public static bool Pixel(char c, int x, int y) { return BitmapFont.Pixel(Glyphs, CellWidth, CellHeight, First, Count, c, x, y); }\n");
            sb.Append("        public static int Width(string text, int scale) { return BitmapFont.Width(CellWidth, text, scale); }\n");
            sb.Append("        public static int Height(string text, int scale) { return BitmapFont.Height(CellHeight, text, scale); }\n");
            sb.Append("        public static void Draw(string text, int x, int y, int color, int scale) { BitmapFont.Draw(Glyphs, CellWidth, CellHeight, First, Count, text, x, y, color, scale); }\n");
            sb.Append("        public static void DrawChar(char c, int x, int y, int color, int scale) { BitmapFont.DrawChar(Glyphs, CellWidth, CellHeight, First, Count, c, x, y, color, scale); }\n");
            sb.Append("        public static int DrawInt(int value, int x, int y, int color, int scale) { return BitmapFont.DrawInt(Glyphs, CellWidth, CellHeight, First, Count, value, x, y, color, scale); }\n");
            sb.Append("    }\n\n");
        }
        sb.Append("}\n");
        if (condition != null) sb.Append("#endif\n");
        return new Output(sb.ToString(), reports, warnings);
    }

    /// <summary>
    /// The SHA-256 (lower-case hex) of an input file as an <c>// input sha256:</c> line of <c>Assets.g.cs</c> gives it. For the manifest
    /// (<paramref name="text"/>) a CR before an LF is left out, so a CRLF checkout of assets.json hashes the same. The library build's
    /// check in src/ESharp.Sdk/buildTransitive/AmigaESharp.Sdk.targets (EsCheckLibraryAssets) computes the same value.
    /// </summary>
    public static string InputHash(byte[] bytes, bool text)
    {
        if (text)
        {
            var kept = new List<byte>(bytes.Length);
            for (var i = 0; i < bytes.Length; i++)
                if (!(bytes[i] == (byte)'\r' && i + 1 < bytes.Length && bytes[i + 1] == (byte)'\n')) kept.Add(bytes[i]);
            bytes = kept.ToArray();
        }
        return Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(bytes)).ToLowerInvariant();
    }

    /// <summary>The longest sample audio.device takes in one write (Sound.MaxLength).</summary>
    public const int MaxSampleLength = 131070;

    public enum SyncStatus { UpToDate, Created, Updated, Touched }

    public sealed record SyncResult(SyncStatus Status, string Target, Output? Output);

    /// <summary>The generated file that belongs to a manifest: <c>Assets.g.cs</c> next to it.</summary>
    public static string TargetPath(string manifestPath) =>
        Path.Combine(Path.GetDirectoryName(Path.GetFullPath(manifestPath))!, "Assets.g.cs");

    /// <summary>The files the generated source depends on: the manifest and every PNG, ILBM or sound file it lists.</summary>
    public static IReadOnlyList<string> Inputs(string manifestPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(manifestPath))!;
        var list = new List<string> { Path.GetFullPath(manifestPath) };
        using var doc = JsonDocument.Parse(File.ReadAllText(manifestPath), new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        foreach (var key in new[] { "images", "samples", "fonts" })
            if (doc.RootElement.TryGetProperty(key, out var images))
                foreach (var e in images.EnumerateArray())
                    if (e.TryGetProperty("file", out var f) && f.GetString() is { } name)
                        list.Add(Path.GetFullPath(Path.Combine(dir, name)));
        return list;
    }

    /// <summary>True when <c>Assets.g.cs</c> is missing or older than the manifest or any listed input file.</summary>
    public static bool IsStale(string manifestPath)
    {
        var target = TargetPath(manifestPath);
        if (!File.Exists(target)) return true;
        var built = File.GetLastWriteTimeUtc(target);
        // A missing PNG counts as stale so that Build reports it.
        return Inputs(manifestPath).Any(i => !File.Exists(i) || File.GetLastWriteTimeUtc(i) > built);
    }

    /// <summary>
    /// Incremental build step: regenerates <c>Assets.g.cs</c> only when it is stale (or <paramref name="force"/>).
    /// The file is rewritten only when the text really changes; if it does not, the file is just touched so
    /// that it is fresh again (the next call is then a no-op and git sees no change).
    /// </summary>
    public static SyncResult Sync(string manifestPath, bool force = false)
    {
        var target = TargetPath(manifestPath);
        if (!force && !IsStale(manifestPath)) return new SyncResult(SyncStatus.UpToDate, target, null);
        var output = Build(manifestPath);
        if (!File.Exists(target))
        {
            File.WriteAllText(target, output.Source);
            return new SyncResult(SyncStatus.Created, target, output);
        }
        if (File.ReadAllText(target) == output.Source)
        {
            // Not older than any input, even one with a future time (clock skew, files from another machine),
            // so the next build is a no-op instead of another regeneration.
            var stamp = DateTime.UtcNow;
            foreach (var i in Inputs(manifestPath))
                if (File.Exists(i) && File.GetLastWriteTimeUtc(i) > stamp) stamp = File.GetLastWriteTimeUtc(i);
            File.SetLastWriteTimeUtc(target, stamp);
            return new SyncResult(SyncStatus.Touched, target, output);
        }
        File.WriteAllText(target, output.Source);
        return new SyncResult(SyncStatus.Updated, target, output);
    }

    private static bool IsIdentifier(string s) =>
        s.Length > 0 && (char.IsLetter(s[0]) || s[0] == '_') && s.All(ch => char.IsLetterOrDigit(ch) || ch == '_');
}
