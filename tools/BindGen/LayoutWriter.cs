using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

/// <summary>
/// Writes src/ESharp.Platform/Layout.g.cs from the measured numbers of <c>bindgen offsets</c> (one "Name = 12" or
/// "Name = 5u" line per item of structs.txt) for AROS x86-64 and m68k, and reads it back. Every number comes from the
/// target's compiler; nothing is typed in. Both targets must list the same names in the same order.
/// </summary>
internal static class LayoutWriter
{
    internal sealed record Entry(string Name, long Value, bool Unsigned);

    private static readonly Regex Measured = new(@"^(\w+) = (-?\d+)(u?)$", RegexOptions.Compiled);
    private static readonly Regex Constant = new(@"^    public const (int|uint) (\w+) = (-?\d+)(u?);$", RegexOptions.Compiled);

    public static List<Entry> ParseMeasured(string text)
    {
        var list = new List<Entry>();
        foreach (var raw in text.Replace("\r\n", "\n").Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0) continue;
            var m = Measured.Match(line);
            if (!m.Success) throw new FormatException($"not a measured value: '{line}' (was every item measured?)");
            list.Add(new Entry(m.Groups[1].Value, long.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture), m.Groups[3].Value == "u"));
        }
        return list;
    }

    public static string Write(IReadOnlyList<Entry> aros, IReadOnlyList<Entry> m68k)
    {
        var an = aros.Select(e => e.Name).ToList();
        var mn = m68k.Select(e => e.Name).ToList();
        if (!an.SequenceEqual(mn))
            throw new InvalidOperationException("the two targets measured different items: " +
                string.Join(", ", an.Except(mn).Concat(mn.Except(an)).DefaultIfEmpty("same names, different order")));
        var sb = new StringBuilder();
        sb.Append("// Generated by tools/BindGen/layouts.sh from tools/BindGen/structs.txt: offsets measured with each target's\n");
        sb.Append("// C compiler and headers (numbers only). Do not edit; re-run the script.\n");
        sb.Append("#if AMIGA\n");
        sb.Append("namespace ESharp.Platform;\n\n");
        sb.Append("/// <summary>Struct offsets, sizes and header constants per target (AmigaOS 3 m68k: 32-bit pointers; AROS x86-64: 64-bit pointers).</summary>\n");
        sb.Append("public static class Layout\n{\n#if X86_64\n");
        foreach (var e in aros) sb.Append(Line(e));
        sb.Append("#else\n");
        foreach (var e in m68k) sb.Append(Line(e));
        sb.Append("#endif\n}\n#endif\n");
        return sb.ToString();
    }

    private static string Line(Entry e) => e.Unsigned
        ? $"    public const uint {e.Name} = {e.Value.ToString(CultureInfo.InvariantCulture)}u;\n"
        : $"    public const int {e.Name} = {e.Value.ToString(CultureInfo.InvariantCulture)};\n";

    /// <summary>The two tables of an existing Layout.g.cs (AROS x86-64 first, then m68k).</summary>
    public static (List<Entry> Aros, List<Entry> M68k) Read(string text)
    {
        var aros = new List<Entry>();
        var m68k = new List<Entry>();
        var current = aros;
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            if (line == "#else") { current = m68k; continue; }
            var m = Constant.Match(line);
            if (m.Success) current.Add(new Entry(m.Groups[2].Value, long.Parse(m.Groups[3].Value, CultureInfo.InvariantCulture), m.Groups[1].Value == "uint"));
        }
        return (aros, m68k);
    }

    /// <summary>The names structs.txt asks for, in order (to check that Layout.g.cs is up to date with it).</summary>
    public static List<string> SpecNames(string spec) =>
        spec.Replace("\r\n", "\n").Split('\n').Select(l => l.Trim())
            .Where(l => l.Length > 0 && !l.StartsWith('#') && !l.StartsWith("include ", StringComparison.Ordinal) && l.Contains('='))
            .Select(l => l.Split('=', 2)[0].Trim()).ToList();
}
