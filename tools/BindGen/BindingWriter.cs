using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

/// <summary>
/// Writes C# binding declarations in the style of src/ESharp.Platform from fd facts (and prototype types when given):
/// <c>[AmigaLib("lib", -vector), Since(n)] public static extern RET Name(T a, ...);</c>, one per public vector, in
/// vector order. Parameters keep the fd/prototype order: the emitter calls the function through the target's own
/// proto header (inline macros on m68k, the interface on AmigaOS 4, AROS stubs), which puts each argument into its
/// register, so the C# order must be the C order. Private and reserved slots are skipped (their vectors still count).
/// </summary>
internal static class BindingWriter
{
    // Opened by the C startup code (libnix, AROS autoinit); every other library needs a base of our own ([LibraryBase]).
    public static readonly HashSet<string> AutoOpened = new() { "exec", "dos", "graphics", "intuition" };

    // Devices whose functions E# calls through the device base.
    private static readonly HashSet<string> Devices = new() { "timer", "console", "input" };

    private static readonly HashSet<string> Keywords = new()
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
        // C keywords too: the parameter names reach the generated C.
        "auto", "register", "signed", "unsigned", "union", "typedef",
    };

    public sealed record Options(string? ClassName = null, bool Docs = false, string? BaseName = null, string Namespace = "ESharp.Platform");

    /// <summary>True for slots that are not part of the public interface even when the fd file lists them as public.</summary>
    public static bool IsPrivate(string name) => Regex.IsMatch(name, @"(?i)private|reserved|^LIB(Open|Close|Expunge|Null)$");

    public static string ParamName(string name)
    {
        if (string.IsNullOrEmpty(name)) return "arg";
        return Keywords.Contains(name) ? name + "Arg" : name;
    }

    /// <summary>"ExecLibrary", "LowlevelLibrary": a name the hand-written platform classes (Exec, DosLib, AslLib, ...) do not use.</summary>
    public static string ClassNameFor(string lib) => char.ToUpperInvariant(lib[0]) + lib.Substring(1) + "Library";

    /// <summary>One declaration line (no indent), plus the number of types the map did not know.</summary>
    public static (string Line, int Unknown) Declaration(string lib, Func f)
    {
        int unknown = 0;
        string T(string c) { var (cs, known) = BindTypes.Map(c); if (!known) unknown++; return cs; }
        string ret = T(f.Ret);
        var ps = f.Args.Select(a => T(a.Type) + " " + ParamName(a.Name));
        string since = f.Since > 0 ? $", Since({f.Since})" : "";
        return ($"[AmigaLib(\"{lib}\", {-6 * f.Lvo}){since}] public static extern {ret} {f.Name}({string.Join(", ", ps)});", unknown);
    }

    public static string Write(string lib, IEnumerable<Func> funcs, Options o)
    {
        var sb = new StringBuilder();
        string cls = o.ClassName ?? ClassNameFor(lib);
        var list = funcs.Where(f => !IsPrivate(f.Name)).OrderBy(f => f.Lvo).ToList();
        sb.AppendLine("// Generated by tools/BindGen from the fd file (and prototypes) of an SDK you provide: names, vectors,");
        sb.AppendLine("// registers, types and first versions only. Review the marked types before use.");
        sb.AppendLine("#if AMIGA");
        if (o.Namespace != "ESharp" && !o.Namespace.StartsWith("ESharp.", StringComparison.Ordinal)) sb.AppendLine("using ESharp;");
        sb.AppendLine($"namespace {o.Namespace};");
        sb.AppendLine();
        if (o.Docs) sb.AppendLine($"/// <summary>{lib}.library bindings generated by tools/BindGen ({list.Count} functions).</summary>");
        bool ownBase = !AutoOpened.Contains(lib);
        if (ownBase)
        {
            string baseName = o.BaseName ?? char.ToUpperInvariant(lib[0]) + lib.Substring(1) + "Base";
            sb.AppendLine($"[LibraryBase(\"{lib}\", \"{baseName}\", \"{(Devices.Contains(lib) ? "struct Device" : "struct Library")}\")]");
        }
        sb.AppendLine($"public static unsafe class {cls}");
        sb.AppendLine("{");
        if (ownBase)
        {
            sb.AppendLine("    /// <summary>Emitter intrinsic: sets the library base the calls below use (from OpenLibrary, or null after closing).</summary>");
            sb.AppendLine("    public static extern void SetBase(void* library);");
            sb.AppendLine();
        }
        int unknown = 0;
        foreach (var f in list)
        {
            var (line, u) = Declaration(lib, f);
            unknown += u;
            if (o.Docs) sb.AppendLine($"    /// <summary>{lib} vector {-6 * f.Lvo}{(f.Since > 0 ? $", v{f.Since}" : "")}{Registers(f)}.</summary>");
            sb.AppendLine((u > 0 ? "    // check the marked type\n" : "") + "    " + line);
        }
        sb.AppendLine("}");
        sb.AppendLine("#endif");
        if (unknown > 0) sb.AppendLine($"// {unknown} type(s) not in the type map, marked above.");
        return sb.ToString().Replace("\r\n", "\n");   // LF on every platform, like the committed bindings
    }

    private static string Registers(Func f)
    {
        var regs = f.Args.Select(a => a.Register).Where(r => r.Length > 0).ToList();
        return regs.Count == 0 ? "" : "; arguments in " + string.Join(", ", regs.Select(r => r.ToLowerInvariant()));
    }
}
