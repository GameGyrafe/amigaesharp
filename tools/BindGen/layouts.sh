#!/usr/bin/env bash
# Regenerates src/ESharp.Platform/Layout.g.cs: the struct offsets E# reads directly, measured with each
# target's own C compiler and headers (tools/BindGen/structs.txt lists them). Needs docker and the two images.
# Usage: tools/BindGen/layouts.sh [m68k image] [aros image]
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"; cd "$root"
m68k="${1:-amigadev/crosstools:m68k-amigaos@sha256:32ec76dac03a642203f0f09f0416480d6c25de1092ed7ed472db870304a64859}"
aros="${2:-amigadev/crosstools@sha256:9c4e978301da6b6584d68d4014caa1fa9e2689529e79e71f7190d40d1cb62e50}"
run() { dotnet run --project tools/BindGen -- offsets tools/BindGen/structs.txt "$1" --docker "$2"; }
a="$(run aros "$aros")"; m="$(run m68k "$m68k")"
emit() { echo "$1" | sed -e 's/^\(.*\) = \([0-9]*\)u$/    public const uint \1 = \2u;/' -e 's/^\([^ ]*\) = \([0-9]*\)$/    public const int \1 = \2;/'; }
{
  echo "// Generated by tools/BindGen/layouts.sh from tools/BindGen/structs.txt: offsets measured with each target's"
  echo "// C compiler and headers (numbers only). Do not edit; re-run the script."
  echo "#if AMIGA"
  echo "namespace ESharp.Platform;"
  echo ""
  echo "/// <summary>Struct offsets, sizes and header constants per target (AmigaOS 3 m68k: 32-bit pointers; AROS x86-64: 64-bit pointers).</summary>"
  echo "public static class Layout"
  echo "{"
  echo "#if X86_64"
  emit "$a"
  echo "#else"
  emit "$m"
  echo "#endif"
  echo "}"
  echo "#endif"
} > src/ESharp.Platform/Layout.g.cs
echo "wrote src/ESharp.Platform/Layout.g.cs"
