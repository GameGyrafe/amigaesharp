        Assert.Contains("#if AMIGA\nnamespace T\n{\n    /// <summary>The fields of the library's Point", binding);

        // A program with the binding and without the library's sources: m68k vector calls through the opener's base in a6.
        const string program = @"using ESharp;
using ESharp.Platform;
using T;
public static unsafe class P
{
    [EntryPoint]
    public static int Main()
    {
        var lib = TestLibrary.Open(3);
