/// <summary>The host side of the bindings: each opener of a library keeps its own copy of the library types' static fields.</summary>
public unsafe class SharedLibraryHostTests
{
    public static class Fixture
    {
        public static int Count = 5;
        public static int[] Table = { 1, 2 };
        public static readonly int[] Fixed = { 7 };
        public static Holder Box = new Holder();
        public static Holder Same = Box;

        public sealed class Holder { public int V; public int[] Items = new int[2]; }
    }

    [Fact]
    public void Each_host_opener_has_its_own_statics_objects_and_arrays()
    {
        var types = typeof(Fixture).FullName!;
        var name = "fixture-" + Guid.NewGuid().ToString("N") + ".library";
        var a = ESharp.Platform.SharedLibrary.Open(name, 1, 1, types);
        var b = ESharp.Platform.SharedLibrary.Open(name, 1, 1, types);
        Assert.True(ESharp.Platform.SharedLibrary.Open(name, 2, 1, types) == null);   // newer than the library
        Assert.Equal(2, ESharp.Platform.SharedLibrary.OpenCount(name));

        ESharp.Platform.SharedLibrary.Enter(a);
        Fixture.Count += 10; Fixture.Table[0] = 99; Fixture.Fixed[0] = 8; Fixture.Box.V = 3; Fixture.Box.Items[1] = 4;
        ESharp.Platform.SharedLibrary.Leave(a);

        ESharp.Platform.SharedLibrary.Enter(b);
        Assert.Equal((5, 1, 7, 0, 0), (Fixture.Count, Fixture.Table[0], Fixture.Fixed[0], Fixture.Box.V, Fixture.Box.Items[1]));
        Assert.Same(Fixture.Box, Fixture.Same);   // shared references stay shared within one opener
        Fixture.Count = 1;
        ESharp.Platform.SharedLibrary.Leave(b);

        ESharp.Platform.SharedLibrary.Enter(a);
        Assert.Equal((15, 99, 8, 3, 4), (Fixture.Count, Fixture.Table[0], Fixture.Fixed[0], Fixture.Box.V, Fixture.Box.Items[1]));
        ESharp.Platform.SharedLibrary.Leave(a);

        ESharp.Platform.SharedLibrary.Close(a);
        ESharp.Platform.SharedLibrary.Close(b);
        Assert.Equal(0, ESharp.Platform.SharedLibrary.OpenCount(name));
        ESharp.Platform.SharedLibrary.FlushUnused();
        Assert.Equal(-1, ESharp.Platform.SharedLibrary.OpenCount(name));
        var c = ESharp.Platform.SharedLibrary.Open(name, 1, 1, types);
        ESharp.Platform.SharedLibrary.Enter(c);
        Assert.Equal((5, 1, 7, 0), (Fixture.Count, Fixture.Table[0], Fixture.Fixed[0], Fixture.Box.V));   // a new opener starts fresh
        ESharp.Platform.SharedLibrary.Leave(c);
        ESharp.Platform.SharedLibrary.Close(c);
    }

}

