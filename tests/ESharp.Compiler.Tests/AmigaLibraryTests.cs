    [Fact]
    public void The_library_C_has_one_data_block_per_opener_and_frees_each_openers_memory()
    {
        if (!HasGcc) return;
        var r = CompileLibrary(Lib);
        Assert.True(r.Success, string.Join("\n", r.Diagnostics));
        var c = r.C!;
        // Every E# variable is a member of the opener's data; nothing of it is a C global.
        Assert.Contains("struct es_user", c);
        Assert.Contains("#define Es_T_Counter__value (ES_USER->Es_T_Counter__value)", c);
        Assert.DoesNotContain("static int32_t Es_T_Counter__value;", c);
        Assert.Contains("static int32_t Es_T_Counter__value__init = 10;", c);   // the start value each opener copies in
        Assert.Contains("register struct es_rt *es_d __asm__(\"a4\");", c);
        // The RomTag right after the first two instructions, and the id and $VER strings.
        Assert.Contains("\"\\t.word 0x4afc\\n\"", c);
        Assert.Contains("\"\\t.byte 0x80,3,9,0\\n\"", c);
        Assert.Contains("\"$VER: test.library 3.7 (25.11.2026)\"", c);
        Assert.Contains("es_lib_entry_Move(uintptr_t p __asm(\"a0\"), uintptr_t dx __asm(\"d0\"), struct es_lib_head *es_base __asm(\"a6\"))", c);
        Assert.DoesNotContain("int main(", c);
        Assert.DoesNotContain("<stdio.h>", c);

        const string main = @"
#include <stdio.h>
#include <stdlib.h>
int main(void)
{
    void *a = calloc(1, ES_LIB_DATA_SIZE), *b = calloc(1, ES_LIB_DATA_SIZE);
    if (a == NULL || b == NULL || !es_lib_data_init(a) || !es_lib_data_init(b)) return 1;
    int a1 = es_lib_call_Add(a, 5);
    int a2 = es_lib_call_Add(a, 1);
    int b1 = es_lib_call_Add(b, 2);
    printf(""add %d %d %d\n"", a1, a2, b1);
    printf(""boxed %d %d\n"", es_lib_call_Boxed(a), es_lib_call_Boxed(b));
    int t1 = es_lib_call_Table(a, 1);
    int t2 = es_lib_call_Table(a, 1);
    int t3 = es_lib_call_Table(b, 1);
    printf(""table %d %d %d\n"", t1, t2, t3);
    Es_T_Point pt = { 3, 4 };
    es_lib_call_Move(a, &pt, 10);
    printf(""point %d %d made %d %d\n"", pt.X, pt.Y, es_lib_call_MadeCount(a), es_lib_call_MadeCount(b));
    printf(""even %d %d name %s len %d fresh %d\n"", es_lib_call_Even(b, 4), es_lib_call_Even(b, 5), es_lib_call_Name(a), es_lib_call_Len(a, ""amiga""), es_lib_call_Fresh(b));
    es_lib_data_fini(a);
    /* A new opener in the same memory starts from the initial values again. */
    __builtin_memset(a, 0, ES_LIB_DATA_SIZE);
    if (!es_lib_data_init(a)) return 1;
    int boxed = es_lib_call_Boxed(a);   /* before Add, which counts in the box too (C leaves the order of printf's arguments open) */
    int again = es_lib_call_Add(a, 0);
    printf(""again %d %d\n"", again, boxed);
    es_lib_data_fini(a);
    es_lib_data_fini(b);
    free(a);
    free(b);
    return 0;
}
";
        var (code, output) = HasSanitizers ? RunSanitized(c + main) : RunWithHostGcc(c + main);
        Assert.True(code == 0, output);
        Assert.Equal("add 15 16 12\nboxed 2 1\ntable 12 22 12\npoint 13 4 made 50 49\neven 1 0 name t len 5 fresh 5\nagain 10 0\n", output);
    }

