/// <summary>
/// Amiga shared libraries from E# (EsOutputType AmigaLibrary, issue #154): the [LibraryFunction] rules, the register assignment, the .fd
/// file and the binding, the library's C built with the host gcc (two openers, each with its own data block, called through the C entries
/// that the m68k vectors use) and the program side's [LibraryCall] vector calls. The real .library runs in FS-UAE (docs/STATUS.md).
/// </summary>
public class AmigaLibraryTests
{
    private static readonly AmigaLibraryOptions Options = new() { Name = "test.library", Version = 3, Revision = 7, Date = "25.11.2026" };

    private const string Lib = @"using ESharp;
using ESharp.Platform;

namespace T;

public struct Point
{
    public int X;
    public int Y;
}

public sealed class Box
{
    public int V;
}

public static unsafe class Counter
{
    private static int _value = 10;
    private static int[] _table = { 1, 2, 3 };
    private static Box _box = new Box();
    public static int Made { get; private set; } = 7;
    private static int _cctor;

    static Counter() { _cctor = 42; }

    [LibraryFunction] public static int Add(int step) { _value += step; _box.V++; return _value; }
    [LibraryFunction] public static int Boxed() { return _box.V; }
    [LibraryFunction] public static int Table(int i) { _table[i] += 10; return _table[i]; }
    [LibraryFunction] public static void Move(Point* p, int dx) { p->X += dx; Made++; }
    [LibraryFunction] public static bool Even(int x) { return (x & 1) == 0; }
    [LibraryFunction] public static string Name() { return ""t""; }
    [LibraryFunction] public static int Len(string s) { return s.Length; }
    [LibraryFunction] public static int MadeCount() { return Made + _cctor; }
    [LibraryFunction] public static int Fresh() { Box b = new Box(); b.V = 5; return b.V; }
}
";

    private static CompileResult CompileLibrary(string source, AmigaLibraryOptions? options = null) =>
        EsCompiler.Compile(new[] { new SourceFile("lib.cs", source) }, new CompileOptions { AmigaLibrary = options ?? Options });

    private static string[] Errors(CompileResult r) => ErrorIds(r);

    [Fact]
    public void Registers_go_data_to_d_and_pointers_to_a_then_spill_into_the_other_kind()
    {
        Assert.Equal(new string[0], AmigaLibraries.AssignRegisters(new bool[0]));
        Assert.Equal(new[] { "d0", "d1", "a0" }, AmigaLibraries.AssignRegisters(new[] { false, false, true }));
        Assert.Equal(new[] { "a0", "d0", "a1", "d1" }, AmigaLibraries.AssignRegisters(new[] { true, false, true, false }));
        // Nine numbers: d0-d7, then the first free address register.
        Assert.Equal(new[] { "d0", "d1", "d2", "d3", "d4", "d5", "d6", "d7", "a0" }, AmigaLibraries.AssignRegisters(Enumerable.Repeat(false, 9).ToList()));
        // Five pointers: a0-a3, then d0 (no numbers to take it).
        Assert.Equal(new[] { "a0", "a1", "a2", "a3", "d0" }, AmigaLibraries.AssignRegisters(Enumerable.Repeat(true, 5).ToList()));
        // Six of each: the numbers keep d0-d5, the fifth and sixth pointers take d6 and d7.
        var mixed = AmigaLibraries.AssignRegisters(new[] { true, true, true, true, true, true, false, false, false, false, false, false })!;
        Assert.Equal(new[] { "a0", "a1", "a2", "a3", "d6", "d7", "d0", "d1", "d2", "d3", "d4", "d5" }, mixed);
        // Ten numbers and two pointers: a0, a1 for the pointers, a2 and a3 for the ninth and tenth numbers.
        var many = AmigaLibraries.AssignRegisters(Enumerable.Repeat(false, 10).Concat(new[] { true, true }).ToList())!;
        Assert.Equal(new[] { "a2", "a3", "a0", "a1" }, many.Skip(8));
        Assert.Null(AmigaLibraries.AssignRegisters(Enumerable.Repeat(false, 13).ToList()));
        // Never a4 (the opener's data in the library), a5 (frame pointer) or a6/a7.
        foreach (var n in Enumerable.Range(0, 13))
            foreach (var kinds in new[] { Enumerable.Repeat(true, n).ToList(), Enumerable.Repeat(false, n).ToList() })
                if (AmigaLibraries.AssignRegisters(kinds) is { } regs)
                {
                    Assert.DoesNotContain(regs, r => r is "a4" or "a5" or "a6" or "a7");
                    Assert.Equal(regs.Count, regs.Distinct().Count());
                }
    }

    [Fact]
    public void The_fd_file_lists_the_functions_in_vector_order_and_BindGen_reads_it_back()
    {
        var r = CompileLibrary(Lib);
        Assert.True(r.Success, string.Join("\n", r.Diagnostics));
        var fd = r.AmigaLibrary!.Fd;
        Assert.StartsWith("* \"test.library\" 3.7: generated by esharp", fd);
        Assert.Contains("##base _TestBase\n##bias 30\n##public\nAdd(step)(d0)\nBoxed()()\nTable(i)(d0)\nMove(p,dx)(a0,d0)\n", fd);
        Assert.EndsWith("MadeCount()()\nFresh()()\n##end\n", fd);
        var funcs = Fd.ParseText(fd);
        Assert.Equal(r.AmigaLibrary.Functions.Select(f => f.Name), funcs.Select(f => f.Name));
        Assert.Equal(r.AmigaLibrary.Functions.Select(f => f.Offset), funcs.Select(f => -6 * f.Lvo));
        Assert.Equal(new[] { "A0", "D0" }, funcs.Single(f => f.Name == "Move").Args.Select(a => a.Register));
        Assert.Equal(-30, r.AmigaLibrary.Functions[0].Offset);
        Assert.Equal(-30 - 6 * 8, r.AmigaLibrary.Functions[8].Offset);
        Assert.Equal("TestBase", Fd.BaseName(fd));
    }

    [Fact]
    public void Library_functions_must_be_public_static_plain_and_named_apart()
    {
        string Src(string members) => "using ESharp;\nnamespace T;\npublic struct S { public int A; public int B { get; set; } }\npublic enum E { One }\npublic class K { }\npublic static unsafe class L\n{\n" + members + "\n}\n";
        Assert.Contains("ES0130", Errors(CompileLibrary(Src("[LibraryFunction] static int F() { return 1; }"))));
        Assert.Contains("ES0130", Errors(CompileLibrary("using ESharp;\nnamespace T;\npublic class L { [LibraryFunction] public int F() { return 1; } }")));
        Assert.Contains("ES0130", Errors(CompileLibrary(Src("[LibraryFunction] public static T F<T>(T x) where T : unmanaged { return x; }"))));
        Assert.Contains("ES0130", Errors(CompileLibrary(Src("[LibraryFunction] public static int Open() { return 1; }"))));       // a member of the binding
        Assert.Contains("ES0130", Errors(CompileLibrary(Src("[LibraryFunction] public static void F(S* s) { }"))));                // a struct with an auto-property
        foreach (var (type, name) in new[] { ("long", "long"), ("ulong", "ulong"), ("K", "T.K"), ("int[]", "int[]"), ("System.Action", "System.Action"), ("E", "T.E"), ("S", "T.S") })
        {
            var r = CompileLibrary(Src($"[LibraryFunction] public static void F({type} x) {{ }}"));
            Assert.Contains("ES0131", Errors(r));
            Assert.Contains(r.Diagnostics, d => d.Id == "ES0131" && d.GetMessage().Contains("'" + name + "'"));
        }
        Assert.Contains("ES0131", Errors(CompileLibrary(Src("[LibraryFunction] public static long F() { return 1; }"))));
        Assert.Contains("ES0131", Errors(CompileLibrary(Src("[LibraryFunction] public static void F(ref int x) { x = 1; }"))));
        var args = string.Join(", ", Enumerable.Range(0, 13).Select(i => "int a" + i));
        Assert.Contains("ES0132", Errors(CompileLibrary(Src($"[LibraryFunction] public static void F({args}) {{ }}"))));
        Assert.Contains("ES0133", Errors(CompileLibrary(Src("public static int F() { return 1; }"))));
        var twice = CompileLibrary("using ESharp;\nnamespace T;\npublic static class A { [LibraryFunction] public static int F() { return 1; } }\npublic static class B { [LibraryFunction] public static int F() { return 2; } }");
        Assert.Contains("ES0135", Errors(twice));
        // Plain values are fine: every integer up to 32 bits, bool, char, string, nint and pointers to numbers, void, pointers and structs of fields.
        var ok = CompileLibrary("using ESharp;\nnamespace T;\npublic unsafe struct P { public int X; public long Big; public byte* Data; }\npublic static unsafe class L\n{\n" +
            "[LibraryFunction] public static uint F(sbyte a, byte b, short c, ushort d, int e, uint f, nint g, nuint h, bool i, char j, string k, long* l) { return 0; }\n" +
            "[LibraryFunction] public static P* G(P* p, void* v, byte** pp) { return p; }\n}\n");
        Assert.True(ok.Success, string.Join("\n", ok.Diagnostics));
        // Ten numbers and two pointers: the ninth and tenth numbers take a2 and a3, which the two pointers (a0, a1) leave free.
        Assert.Equal(new[] { "d0", "d1", "d2", "d3", "d4", "d5", "d6", "d7", "a2", "a3", "a0", "a1" }, ok.AmigaLibrary!.Functions[0].Arguments.Select(a => a.Register));
    }

